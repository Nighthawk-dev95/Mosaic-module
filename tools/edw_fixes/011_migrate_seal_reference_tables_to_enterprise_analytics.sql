CREATE TABLE IF NOT EXISTS edw_prod.enterprise_analytics.tbl_seal_roster
COMMENT 'Governed copy of edw_dev.bipa_analytics.stg_seal_roster, materialized so the mosaic-module app (service principal scoped to enterprise_analytics only, confirmed via SHOW GRANTS 2026-10-14) can read it without a cross-catalog grant. Re-run this CTAS whenever the source roster changes (practice-director-provided file, see memory: seal-roster-reconciliation). 118 rows / 95 active as of 2026-10-14.'
AS SELECT
  NPI,
  Last_Name,
  First_Name,
  Is_Active
FROM edw_dev.bipa_analytics.stg_seal_roster;

CREATE TABLE IF NOT EXISTS edw_prod.enterprise_analytics.tbl_seal_baseline_master
COMMENT 'Governed copy of edw_dev.bipa_analytics.stg_seal_baseline_master, materialized so the mosaic-module app can read it without a cross-catalog grant (see tbl_seal_roster for the same rationale). Re-run this CTAS every time SEAL Team Re-Baselining.ipynb overwrites the source table - ideally as that notebook'' own final step, so this never drifts stale. 105 rows as of 2026-10-14.'
AS SELECT
  NPI,
  Practice,
  Radiologist,
  Shift_Name,
  Shift_Baseline,
  Shift_Length,
  Units,
  Qgenda_Company_Key,
  Shift_Baseline_TBWU,
  Conversion_Ratio_2025_local,
  Shift_Baseline_TBWU_2026,
  Baseline_Window,
  Baseline_Type
FROM edw_dev.bipa_analytics.stg_seal_baseline_master;

